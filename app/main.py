"""OrderDesk: a small order-entry app for a mock trading desk.

Pages:  /login, /orders/new (order ticket), /orders (blotter)
API:    /api/login, /api/logout, /api/orders, /api/orders/{id}, /api/orders/{id}/cancel
Docs:   /docs (auto-generated by FastAPI)
"""
import os
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import Depends, FastAPI, Form, HTTPException, Request
from fastapi.responses import RedirectResponse
from fastapi.staticfiles import StaticFiles
from fastapi.templating import Jinja2Templates
from pydantic import ValidationError
from sqlalchemy import select
from sqlalchemy.orm import Session
from starlette.middleware.sessions import SessionMiddleware

from app.auth import hash_password, verify_password
from app.db import Base, SessionLocal, engine, get_db
from app.models import Order, User
from app.schemas import ORDER_TYPES, SYMBOLS, LoginIn, OrderIn, OrderOut

BASE_DIR = Path(__file__).parent
SEED_USERS = [("trader", "trader123", "trader"), ("viewer", "viewer123", "viewer")]


def seed_users() -> None:
    with SessionLocal() as db:
        for username, password, role in SEED_USERS:
            if not db.scalar(select(User).where(User.username == username)):
                db.add(User(username=username, password_hash=hash_password(password), role=role))
        db.commit()


@asynccontextmanager
async def lifespan(app: FastAPI):
    Base.metadata.create_all(engine)
    seed_users()
    yield


app = FastAPI(title="OrderDesk", lifespan=lifespan)
app.add_middleware(SessionMiddleware, secret_key=os.getenv("SECRET_KEY", "dev-only-change-me"))
app.mount("/static", StaticFiles(directory=BASE_DIR / "static"), name="static")
templates = Jinja2Templates(directory=BASE_DIR / "templates")


# ---------- auth helpers ----------

def get_current_user(request: Request, db: Session = Depends(get_db)) -> User | None:
    user_id = request.session.get("user_id")
    return db.get(User, user_id) if user_id else None


def require_user(user: User | None = Depends(get_current_user)) -> User:  # REQ-11
    if user is None:
        raise HTTPException(status_code=401, detail="Not authenticated")
    return user


def require_trader(user: User = Depends(require_user)) -> User:  # REQ-02
    if user.role != "trader":
        raise HTTPException(status_code=403, detail="Viewers cannot submit or cancel orders")
    return user


def friendly_errors(exc: ValidationError) -> list[str]:
    return [err["msg"].removeprefix("Value error, ") for err in exc.errors()]


# ---------- business logic (shared by pages and API) ----------

def create_order(db: Session, user: User, data: OrderIn) -> Order:
    order = Order(user_id=user.id, **data.model_dump())
    db.add(order)
    db.commit()
    db.refresh(order)
    return order


def cancel_order(db: Session, user: User, order_id: int) -> Order:  # REQ-09
    if user.role != "trader":
        raise HTTPException(status_code=403, detail="Viewers cannot submit or cancel orders")
    order = db.get(Order, order_id)
    if order is None:
        raise HTTPException(status_code=404, detail="Order not found")
    if order.status != "NEW":
        raise HTTPException(status_code=409, detail="Only NEW orders can be cancelled")
    order.status = "CANCELLED"
    db.commit()
    db.refresh(order)
    return order


# ---------- HTML pages ----------

@app.get("/")
def home(user: User | None = Depends(get_current_user)):
    return RedirectResponse("/orders" if user else "/login", status_code=303)


@app.get("/login")
def login_page(request: Request):
    return templates.TemplateResponse(request, "login.html", {"user": None, "error": None, "username": ""})


@app.post("/login")
def login_submit(
    request: Request,
    username: str = Form(""),
    password: str = Form(""),
    db: Session = Depends(get_db),
):
    user = db.scalar(select(User).where(User.username == username))
    if user is None or not verify_password(password, user.password_hash):  # REQ-01
        return templates.TemplateResponse(
            request,
            "login.html",
            {"user": None, "error": "Invalid username or password", "username": username},
            status_code=401,
        )
    request.session["user_id"] = user.id
    return RedirectResponse("/orders", status_code=303)


@app.post("/logout")
def logout(request: Request):
    request.session.clear()
    return RedirectResponse("/login", status_code=303)


def ticket_context(user, errors=None, form=None):
    return {
        "user": user,
        "symbols": SYMBOLS,
        "order_types": ORDER_TYPES,
        "errors": errors or [],
        "form": form or {},
    }


@app.get("/orders/new")
def order_ticket(request: Request, user: User | None = Depends(get_current_user)):
    if user is None:
        return RedirectResponse("/login", status_code=303)
    return templates.TemplateResponse(request, "order_new.html", ticket_context(user))


@app.post("/orders/new")
def order_ticket_submit(
    request: Request,
    symbol: str = Form(""),
    side: str = Form(""),
    qty: str = Form(""),
    order_type: str = Form(""),
    price: str = Form(""),
    user: User | None = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    if user is None:
        return RedirectResponse("/login", status_code=303)
    form = {"symbol": symbol, "side": side, "qty": qty, "order_type": order_type, "price": price}
    if user.role != "trader":
        return templates.TemplateResponse(
            request, "order_new.html", ticket_context(user, ["Viewers cannot submit orders"], form), status_code=403
        )
    try:
        data = OrderIn(**form)
    except ValidationError as exc:
        return templates.TemplateResponse(
            request, "order_new.html", ticket_context(user, friendly_errors(exc), form), status_code=422
        )
    order = create_order(db, user, data)
    return RedirectResponse(f"/orders?created={order.id}", status_code=303)  # REQ-08


@app.get("/orders")
def blotter(
    request: Request,
    created: int | None = None,
    error: str | None = None,
    user: User | None = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    if user is None:
        return RedirectResponse("/login", status_code=303)
    orders = db.scalars(select(Order).order_by(Order.id.desc())).all()
    return templates.TemplateResponse(
        request, "orders.html", {"user": user, "orders": orders, "created": created, "error": error}
    )


@app.post("/orders/{order_id}/cancel")
def cancel_from_blotter(
    order_id: int,
    user: User | None = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    if user is None:
        return RedirectResponse("/login", status_code=303)
    try:
        cancel_order(db, user, order_id)
    except HTTPException as exc:
        return RedirectResponse(f"/orders?error={exc.detail}", status_code=303)
    return RedirectResponse("/orders", status_code=303)


# ---------- REST API ----------

@app.post("/api/login")
def api_login(body: LoginIn, request: Request, db: Session = Depends(get_db)):
    user = db.scalar(select(User).where(User.username == body.username))
    if user is None or not verify_password(body.password, user.password_hash):
        raise HTTPException(status_code=401, detail="Invalid username or password")
    request.session["user_id"] = user.id
    return {"username": user.username, "role": user.role}


@app.post("/api/logout")
def api_logout(request: Request):
    request.session.clear()
    return {"ok": True}


@app.get("/api/orders", response_model=list[OrderOut])
def api_list_orders(user: User = Depends(require_user), db: Session = Depends(get_db)):
    return db.scalars(select(Order).order_by(Order.id.desc())).all()


@app.get("/api/orders/{order_id}", response_model=OrderOut)
def api_get_order(order_id: int, user: User = Depends(require_user), db: Session = Depends(get_db)):
    order = db.get(Order, order_id)
    if order is None:
        raise HTTPException(status_code=404, detail="Order not found")
    return order


@app.post("/api/orders", response_model=OrderOut, status_code=201)
def api_create_order(data: OrderIn, user: User = Depends(require_trader), db: Session = Depends(get_db)):
    return create_order(db, user, data)


@app.post("/api/orders/{order_id}/cancel", response_model=OrderOut)
def api_cancel_order(order_id: int, user: User = Depends(require_user), db: Session = Depends(get_db)):
    return cancel_order(db, user, order_id)
